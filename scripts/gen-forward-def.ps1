<#
.SYNOPSIS
    Writes a .def file that forwards every export (named and ordinal-only)
    of a system DLL to that DLL by absolute path. Used to build the
    dwmapi.dll proxy.
#>
param(
    [Parameter(Mandatory)] [string]$Dll,
    [Parameter(Mandatory)] [string]$Out,
    [Parameter(Mandatory)] [string]$LibraryName,
    [string[]]$Extra = @()
)

$ErrorActionPreference = 'Stop'
$b = [IO.File]::ReadAllBytes($Dll)

function U16($o) { [BitConverter]::ToUInt16($b, $o) }
function U32($o) { [BitConverter]::ToUInt32($b, $o) }

$pe = [BitConverter]::ToInt32($b, 0x3C)
$opt = $pe + 24
$dd = if ((U16 $opt) -eq 0x20b) { $opt + 112 } else { $opt + 96 }
$expRva = U32 $dd
$nsec = U16 ($pe + 6)
$secTable = $pe + 24 + (U16 ($pe + 20))
$sections = foreach ($i in 0..($nsec - 1)) {
    $s = $secTable + $i * 40
    [pscustomobject]@{ Va = (U32 ($s + 12)); Size = [Math]::Max((U32 ($s + 8)), (U32 ($s + 16))); Raw = (U32 ($s + 20)) }
}
function Off($rva) {
    foreach ($s in $sections) { if ($rva -ge $s.Va -and $rva -lt $s.Va + $s.Size) { return $rva - $s.Va + $s.Raw } }
    throw "RVA $rva not in any section"
}
function CStr($o) { $e = $o; while ($b[$e] -ne 0) { $e++ }; [Text.Encoding]::ASCII.GetString($b, $o, $e - $o) }

$e = Off $expRva
$base = U32 ($e + 16)
$nFuncs = U32 ($e + 20)
$nNames = U32 ($e + 24)
$funcs = Off (U32 ($e + 28))
$names = Off (U32 ($e + 32))
$ords = Off (U32 ($e + 36))

$nameOf = @{}
for ($i = 0; $i -lt $nNames; $i++) {
    $nameOf[[int](U16 ($ords + 2 * $i))] = CStr (Off (U32 ($names + 4 * $i)))
}

$target = [IO.Path]::Combine([IO.Path]::GetDirectoryName($Dll), [IO.Path]::GetFileNameWithoutExtension($Dll))
$lines = @(
    "; Generated by scripts/gen-forward-def.ps1 from $Dll",
    "LIBRARY $LibraryName",
    'EXPORTS'
)
for ($i = 0; $i -lt $nFuncs; $i++) {
    if ((U32 ($funcs + 4 * $i)) -eq 0) { continue }
    $ord = $base + $i
    if ($nameOf.ContainsKey($i)) {
        $lines += "    $($nameOf[$i]) = `"$target.$($nameOf[$i])`" @$ord"
    } else {
        $lines += "    ord$ord = `"$target.#$ord`" @$ord NONAME"
    }
}
$lines += $Extra | ForEach-Object { "    $_" }
Set-Content -Path $Out -Value $lines -Encoding ascii
